//! What keeps a dictation from landing, decided before any event is sent.
//!
//! Windows drops synthetic input into a window of a higher integrity level
//! (UIPI: an app run as administrator) without an error, so the text would
//! vanish. The Mac counterpart is Secure Input; there the text goes to the
//! clipboard and the HUD says «вставьте ⌘V» — the same here with Ctrl+V,
//! which the user's own keyboard may still send.

#[cfg(test)]
mod tests {
    use super::{clipboard_markers, input_blocked, IntegrityLevel, Marker};

    #[test]
    fn integrity_levels_come_from_the_token_rid() {
        assert_eq!(IntegrityLevel::from_rid(0x0000), IntegrityLevel::Untrusted);
        assert_eq!(IntegrityLevel::from_rid(0x1000), IntegrityLevel::Low);
        assert_eq!(IntegrityLevel::from_rid(0x2000), IntegrityLevel::Medium);
        assert_eq!(IntegrityLevel::from_rid(0x2100), IntegrityLevel::Medium);
        assert_eq!(IntegrityLevel::from_rid(0x3000), IntegrityLevel::High);
        assert_eq!(IntegrityLevel::from_rid(0x4000), IntegrityLevel::System);
    }

    #[test]
    fn only_a_window_above_us_blocks_input() {
        use IntegrityLevel::{High, Low, Medium, System};
        assert!(input_blocked(Medium, High));
        assert!(input_blocked(Medium, System));
        assert!(!input_blocked(Medium, Medium));
        assert!(!input_blocked(Medium, Low));
        assert!(!input_blocked(High, High));
    }

    /// Mac: `org.nspasteboard.AutoGeneratedType`. Windows: clipboard managers
    /// and Win+V history skip content carrying these formats.
    #[test]
    fn dictations_on_the_clipboard_stay_out_of_clipboard_history() {
        assert_eq!(
            clipboard_markers(),
            [
                Marker {
                    format: "ExcludeClipboardContentFromMonitorProcessing",
                    dword: None
                },
                Marker {
                    format: "CanIncludeInClipboardHistory",
                    dword: Some(0)
                },
                Marker {
                    format: "CanUploadToCloudClipboard",
                    dword: Some(0)
                },
            ]
        );
    }
}
